#!/usr/bin/env bash
# Bootstrap the host/Android toolchain without `gclient runhooks`.
#
# `gclient runhooks` cannot run here: gclient shells out to `git diff` inside
# every DEPS checkout, and the official tarball has no per-dep git metadata.
# We therefore do the two things Android builds actually need:
#   1. fetch the Chromium clang package from GCS (tools/clang/scripts/update.py)
#   2. synthesize build/util/LASTCHANGE* (normally written by a git hook)
set -euo pipefail
source "$(dirname "$0")/../lib/common.sh"
[[ -d "$CHROMIUM_SRC" ]] || die "missing $CHROMIUM_SRC"

VER="$(tr '\n' ' ' < "$CHROMIUM_SRC/chrome/VERSION" | sed 's/ //g')"

step "clang ($VER)"
if [[ -x "$CHROMIUM_SRC/third_party/llvm-build/Release+Asserts/bin/clang" ]]; then
  log "clang already present"
else
  ( cd "$CHROMIUM_SRC" && python3 tools/clang/scripts/update.py ) \
    || die "clang update failed (needs GCS access: chromium-browser-clang)"
fi

step "gclient_args.gni (generated by gclient sync; tarball ships the wrong defaults)"
GA="$CHROMIUM_SRC/build/config/gclient_args.gni"
python3 - "$GA" <<'PY2'
import re, sys
p = sys.argv[1]
s = open(p).read()
def setv(key, val):
    global s
    if re.search(rf'^{key} = .*$', s, re.M):
        s = re.sub(rf'^{key} = .*$', f'{key} = {val}', s, flags=re.M)
    else:
        s += f'{key} = {val}\n'
setv('checkout_android', 'true')
setv('checkout_android_prebuilts_build_tools', 'true')
setv('checkout_openxr', 'false')
open(p, 'w').write(s)
PY2
grep -E "^checkout_android|^checkout_openxr" "$GA" || true

step "LASTCHANGE"
# version.py requires a 40-char revision prefix; the real value would come from
# a git hook. Keep it synthetic and stable.
# NOTE: build/util/version.py parses LASTCHANGE as KEY=VALUE lines, and
# *LASTCHANGE:* in version templates is "hash-refs/heads/main".
LC='0123456789abcdef0123456789abcdef01234567'
printf 'LASTCHANGE=%s-refs/heads/main\n' "$LC" > "$CHROMIUM_SRC/build/util/LASTCHANGE"
printf 'LASTCHANGE=%s-refs/heads/main\n' "$LC" > "$CHROMIUM_SRC/build/util/LASTCHANGE.blink"
date +%s > "$CHROMIUM_SRC/build/util/LASTCHANGE.committime"

step "verify"
for p in \
  third_party/llvm-build/Release+Asserts/bin/clang \
  third_party/android_toolchain/ndk \
  third_party/android_sdk/public/build-tools \
  third_party/android_deps/autorolled \
  third_party/kotlinc/current ; do
  if [[ -e "$CHROMIUM_SRC/$p" ]]; then log "ok   $p"; else warn "MISS $p"; fi
done
log "next: scripts/chromium/build.sh a"
